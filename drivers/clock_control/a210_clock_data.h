/*
 * Descriptor constructors. reg is the register offset in the bank, shift and
 * width locate the field, and min and max bound the divider field value.
 */
#define NO_SYNC   A210_CLOCK_NO_SYNC
#define PROPAGATE A210_CLOCK_PROPAGATE

#define FIXED(source) {A210_FIXED, 0, 0, 0, source, 0, 0, 0, NO_SYNC, 0}

#define FACTOR(parent, mul, div) {A210_FACTOR, 0, 0, parent, mul, div, 0, 0, NO_SYNC, PROPAGATE}

#define PLL(reg, parent, pll) {A210_PLL, BANK_PLL, reg, parent, PROFILE_##pll, 0, 0, 0, NO_SYNC, 0}

#define POSTDIV(reg, parent) {A210_POSTDIV, BANK_PLL, reg, parent, 0, 0, 0, 0, NO_SYNC, PROPAGATE}

#define DIV(bank, reg, shift, width, parent, min, max)                                             \
	{A210_DIV, BANK_##bank, reg, parent, min, max, shift, width, NO_SYNC, PROPAGATE}

#define SYNC_DIV(bank, reg, shift, width, sync, parent, min, max)                                  \
	{A210_DIV, BANK_##bank, reg, parent, min, max, shift, width, sync, PROPAGATE}

#define NPARENTS(mux) (PARENTS_##mux##_END - PARENTS_##mux + 1)
#define MUX(bank, reg, shift, width, mux, flags)                                                   \
	{A210_MUX, BANK_##bank, reg, 0, PARENTS_##mux, NPARENTS(mux), shift, width, NO_SYNC, flags}

#define GATE(bank, reg, bit, parent)                                                               \
	{A210_GATE, BANK_##bank, reg, parent, 0, 0, bit, 1, NO_SYNC, PROPAGATE}

#define AON(reg) {A210_AON, BANK_AON, reg, 0, 0, 0, 0, 0, NO_SYNC, 0}

